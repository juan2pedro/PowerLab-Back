-- ============================================================
-- V13: Extrae block_name de training_session_template a una
--      entidad propia `block` (mesociclo).
--
-- Cada block_name distinto pasa a ser una fila de `block`; los
-- dias (training_session_template) se reenganchan por block_id.
-- Se impide duplicar un dia del bloque con
-- UNIQUE(block_id, week_number, day_index).
-- ============================================================

-- 1. Nueva tabla del mesociclo
create table block (
    id         bigint generated by default as identity,
    name       varchar(100)                not null,
    notes      varchar(1000),
    created_at timestamp(6) with time zone not null default now(),
    primary key (id)
);

-- 2. Una fila `block` por cada nombre distinto ya existente
insert into block (name)
select distinct block_name
from training_session_template;

-- 3. Nueva FK en los dias (nullable de momento para poder backfillear)
alter table training_session_template
    add column block_id bigint;

update training_session_template tst
set block_id = b.id
from block b
where b.name = tst.block_name;

-- 4. Ya con todos los dias apuntando a su bloque, se exige obligatorio
alter table training_session_template
    alter column block_id set not null;

alter table training_session_template
    add constraint fk_session_template_block
        foreign key (block_id) references block;

-- 5. Un bloque no puede repetir el mismo dia de la misma semana
alter table training_session_template
    add constraint uq_session_template_block_week_day
        unique (block_id, week_number, day_index);

-- 6. Fuera la columna de texto suelta
alter table training_session_template
    drop column block_name;
