-- ============================================================
-- V14: Tablas base de la rama multi-usuario.
--
-- Las entidades User, Bodyweight y PersonalRecord se anadieron
-- al modelo JPA sin su DDL; con ddl-auto=validate el arranque
-- fallaba con "missing table [body_weight]". Se crean aqui en
-- orden de dependencias: users -> body_weight / personal_record.
-- ============================================================

-- 1. Usuario
create table users (
    id                    bigint generated by default as identity,
    email                 varchar(255)                not null,
    password_hash         varchar(255)                not null,
    username              varchar(255)                not null,
    sex                   varchar(20) check (sex in ('MALE', 'FEMALE')),
    coach                 boolean                     not null default false,
    date_of_birth         date,
    created_at            timestamp(6) with time zone,
    updated_at            timestamp(6) with time zone,
    default_pr_visibility varchar(20)                 not null default 'PRIVATE'
                              check (default_pr_visibility in ('PUBLIC', 'PRIVATE', 'COACHES_ONLY')),
    active                boolean                     not null default true,
    primary key (id),
    constraint uq_users_email unique (email),
    constraint uq_users_username unique (username)
);

-- 2. Registro de peso corporal
create table body_weight (
    id      bigint generated by default as identity,
    user_id bigint not null,
    date    date,
    weight  double precision,
    notes   varchar(255),
    primary key (id),
    constraint fk_body_weight_user foreign key (user_id) references users
);

-- 3. Record personal
create table personal_record (
    id            bigint generated by default as identity,
    user_id       bigint      not null,
    exercise_id   bigint      not null,
    achieved_on   date        not null,
    value_kg      double precision not null,
    bodyweight_kg double precision,
    context       varchar(20) not null
                      check (context in ('COMPETITION', 'TRAINING_BLOCK', 'FREE_TRAINING', 'DECLARED')),
    context_label varchar(255),
    source_set_id bigint,
    note          varchar(255),
    primary key (id),
    constraint fk_personal_record_user foreign key (user_id) references users,
    constraint fk_personal_record_exercise foreign key (exercise_id) references exercise,
    constraint fk_personal_record_source_set foreign key (source_set_id) references workout_set
);
