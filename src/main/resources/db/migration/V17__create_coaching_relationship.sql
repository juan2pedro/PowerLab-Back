-- ============================================================
-- V17: Relacion coach <-> atleta (Fase 3, slice minimo para que
--      un coach pueda leer las metricas de sus atletas).
--
--   Tabla con estado (PENDING/ACTIVE/REVOKED/DECLINED). La invariante
--   "1 coach activo por atleta" se fuerza con un indice unico PARCIAL
--   sobre athlete_id donde status='ACTIVE' (mismo patron que el unique
--   de workout). Migrar a N:M en el futuro = quitar ese indice.
-- ============================================================

create table coaching_relationship (
    id           bigint generated by default as identity,
    coach_id     bigint      not null,
    athlete_id   bigint      not null,
    status       varchar(20) not null
                     check (status in ('PENDING', 'ACTIVE', 'REVOKED', 'DECLINED')),
    initiated_by varchar(20) not null
                     check (initiated_by in ('COACH', 'ATHLETE')),
    invite_code  varchar(255),
    created_at   timestamp(6) with time zone,
    responded_at timestamp(6) with time zone,
    primary key (id),
    constraint fk_coaching_coach   foreign key (coach_id)   references users,
    constraint fk_coaching_athlete foreign key (athlete_id) references users
);

-- Un atleta solo puede tener UN coach activo a la vez.
create unique index uq_coaching_active_athlete
    on coaching_relationship (athlete_id)
    where status = 'ACTIVE';
